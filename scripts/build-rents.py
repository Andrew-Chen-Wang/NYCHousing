"""Turn StreetEasy's median asking rent CSV into src/content/rents.generated.ts.

Source: StreetEasy Data Dashboard, "Median Asking Rent, All Apartments"
(https://streeteasy.com/blog/data-dashboard/). Each value is the month's median asking
rent. We publish the mean of the latest 12 monthly medians (skipping blank months) so
one odd month doesn't swing a small neighborhood, plus the latest month and the
2019 mean for comparison. Neighborhoods with fewer than 6 months of data are dropped.

Run: python3 -I scripts/build-rents.py data/streeteasy-median-asking-rent-all.csv
"""

import csv
import json
import sys

path = sys.argv[1]
rows = list(csv.reader(open(path, newline="")))
header = rows[0]
months = header[3:]
last12 = months[-12:]
y2019 = [m for m in months if m.startswith("2019-")]


def mean(vals):
    vals = [float(v) for v in vals if v.strip()]
    return (round(sum(vals) / len(vals)), len(vals)) if vals else (None, 0)


out = []
for r in rows[1:]:
    name, borough, kind = r[0], r[1], r[2]
    data = dict(zip(months, r[3:]))
    avg, n = mean([data[m] for m in last12])
    if avg is None or n < 6:
        continue
    avg19, _ = mean([data[m] for m in y2019])
    latest = next((float(data[m]) for m in reversed(months) if data[m].strip()), None)
    out.append(
        {
            "name": name,
            "borough": borough or "Citywide",
            "kind": kind,
            "avg12": avg,
            "months": n,
            "latest": round(latest) if latest else None,
            "avg2019": avg19,
        }
    )

ts = [
    "// Generated by scripts/build-rents.py from StreetEasy's median asking rent data. Do not edit.",
    f'export const RENT_WINDOW = {{ from: "{last12[0]}", to: "{last12[-1]}" }} as const',
    "export type RentRow = { name: string; borough: string; kind: string; avg12: number; months: number; latest: number | null; avg2019: number | null }",
    "export const RENTS: RentRow[] = " + json.dumps(out, indent=2),
    "",
]
open("src/content/rents.generated.ts", "w").write("\n".join(ts))
print(len(out), "areas", last12[0], "to", last12[-1])
